<?php

namespace App\Services;

use Ace\Application;

class AutoPayoutService
{
    /**
     * Scan and process auto-completion for past events and automatically generate
     * payout requests for completed events whose net earnings have not been requested.
     *
     * @return array Summary of processed events and generated payouts
     */
    public function processAutoPayouts(): array
    {
        if (!auto_payout_enabled()) {
            return [
                'enabled' => false,
                'completed_events' => 0,
                'created_payouts' => [],
                'total_amount' => 0.00
            ];
        }

        $db = Application::$app->db->pdo;
        $completionHours = event_completion_hours();
        $delayMinutes = auto_payout_delay_minutes();

        // 1. Auto-complete active events that have passed their live completion window
        $stmt = $db->prepare("
            SELECT id, organizer_id, name, date 
            FROM events 
            WHERE status = 'published' 
              AND date <= NOW() - INTERVAL " . (int)$completionHours . " HOUR
        ");
        $stmt->execute();
        $eventsToComplete = $stmt->fetchAll(\PDO::FETCH_ASSOC) ?: [];

        $completedCount = 0;
        foreach ($eventsToComplete as $evt) {
            $upd = $db->prepare("UPDATE events SET status = 'completed', updated_at = NOW() WHERE id = :id");
            $upd->execute(['id' => $evt['id']]);

            // Unassign all staff roles for this completed event
            $unassign = $db->prepare("DELETE FROM event_staff_assignments WHERE event_id = :event_id");
            $unassign->execute(['event_id' => $evt['id']]);
            $completedCount++;
        }

        // 2. Query completed events eligible for auto-payout request:
        // Either:
        // - Event marked completed and updated_at is older than delayMinutes
        // - Or event date + completionHours + delayMinutes is in the past
        $stmt = $db->prepare("
            SELECT e.id, e.organizer_id, e.name as event_name, e.pass_fee, e.date, e.updated_at,
                   u.name as host_name, u.email
            FROM events e
            INNER JOIN users u ON e.organizer_id = u.id
            WHERE e.status = 'completed'
              AND (
                  e.updated_at <= NOW() - INTERVAL :delay MINUTE
                  OR e.date <= NOW() - INTERVAL :total_minutes MINUTE
              )
            ORDER BY e.id ASC
        ");
        $stmt->execute([
            'delay' => (int)$delayMinutes,
            'total_minutes' => (int)($completionHours * 60 + $delayMinutes)
        ]);
        $completedEvents = $stmt->fetchAll(\PDO::FETCH_ASSOC) ?: [];

        $createdPayouts = [];
        $totalAmountCreated = 0.00;
        $hostService = new HostService();

        foreach ($completedEvents as $event) {
            // A. Calculate total net revenue generated by this specific event
            $revStmt = $db->prepare("
                SELECT SUM(
                    CASE WHEN e.pass_fee = 1 THEN t.price ELSE t.price * 0.95 END
                )
                FROM tickets t
                INNER JOIN events e ON t.event_id = e.id
                WHERE e.id = :event_id AND t.status IN ('Paid', 'Comped')
            ");
            $revStmt->execute(['event_id' => $event['id']]);
            $eventNetRevenue = (float)($revStmt->fetchColumn() ?: 0.00);

            if ($eventNetRevenue <= 0.00) {
                // Free event or no ticket sales
                continue;
            }

            // B. Check existing payouts for this event (pending, processed, or completed)
            $payoutStmt = $db->prepare("
                SELECT COALESCE(SUM(amount), 0)
                FROM payouts
                WHERE event_id = :event_id 
                  AND status IN ('pending', 'processed', 'completed')
            ");
            $payoutStmt->execute(['event_id' => $event['id']]);
            $existingPayoutsForEvent = (float)($payoutStmt->fetchColumn() ?: 0.00);

            $unrequestedAmount = round(max(0.00, $eventNetRevenue - $existingPayoutsForEvent), 2);
            if ($unrequestedAmount <= 0.00) {
                // Already requested or disbursed
                continue;
            }

            // C. Verify host's overall available balance to prevent over-withdrawal
            $hostStats = $hostService->getDashboardStats($event['organizer_id']);
            $availableHostBalance = (float)($hostStats['availableBalance'] ?? 0.00);

            $amountToRequest = round(min($unrequestedAmount, $availableHostBalance), 2);
            if ($amountToRequest <= 0.00) {
                continue;
            }

            // D. Insert automatic payout request
            $insStmt = $db->prepare("
                INSERT INTO payouts (organizer_id, event_id, amount, type, status, created_at)
                VALUES (:org_id, :evt_id, :amount, 'auto_completed', 'pending', NOW())
            ");
            $insStmt->execute([
                'org_id' => $event['organizer_id'],
                'evt_id' => $event['id'],
                'amount' => $amountToRequest
            ]);

            $payoutId = (int)$db->lastInsertId();
            $createdPayouts[] = [
                'payout_id' => $payoutId,
                'event_id' => $event['id'],
                'event_name' => $event['event_name'],
                'organizer_id' => $event['organizer_id'],
                'host_name' => $event['host_name'] ?? 'Organizer',
                'amount' => $amountToRequest,
                'pass_fee' => (int)($event['pass_fee'] ?? 1)
            ];
            $totalAmountCreated += $amountToRequest;
        }

        return [
            'enabled' => true,
            'completed_events' => $completedCount,
            'created_payouts' => $createdPayouts,
            'total_amount' => $totalAmountCreated
        ];
    }
}