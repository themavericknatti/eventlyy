<?php

namespace App\Services;

use Ace\Application;

class AutoPayoutService
{
    /**
     * Scan and process auto-completion for past events and automatically generate
     * payout requests for completed events whose net earnings have not been requested.
     *
     * @return array Summary of processed events and generated payouts
     */
    public function processAutoPayouts(): array
    {
        $db = Application::$app->db->pdo;
        self::ensureTicketsPassFeeColumn($db);
        self::reconcileDiscountedTickets($db);

        if (!auto_payout_enabled()) {
            return [
                'enabled' => false,
                'completed_events' => 0,
                'created_payouts' => [],
                'total_amount' => 0.00
            ];
        }

        $completionHours = event_completion_hours();
        $delayMinutes = auto_payout_delay_minutes();

        // 1. Auto-complete active events that have passed their live completion window
        $stmt = $db->prepare("
            SELECT id, organizer_id, name, date 
            FROM events 
            WHERE status = 'published' 
              AND date <= NOW() - INTERVAL " . (int)$completionHours . " HOUR
        ");
        $stmt->execute();
        $eventsToComplete = $stmt->fetchAll(\PDO::FETCH_ASSOC) ?: [];

        $completedCount = 0;
        foreach ($eventsToComplete as $evt) {
            $upd = $db->prepare("UPDATE events SET status = 'completed', updated_at = NOW() WHERE id = :id");
            $upd->execute(['id' => $evt['id']]);

            // Unassign all staff roles for this completed event
            $unassign = $db->prepare("DELETE FROM event_staff_assignments WHERE event_id = :event_id");
            $unassign->execute(['event_id' => $evt['id']]);

            // Auto-close and expire any pending staff requests for this completed event
            $closeReq = $db->prepare("
                UPDATE event_staff_requests 
                SET status = 'expired', updated_at = NOW() 
                WHERE event_id = :event_id AND status IN ('pending', 'partially_fulfilled')
            ");
            $closeReq->execute(['event_id' => $evt['id']]);
            $completedCount++;
        }

        // Auto-expire any incomplete layaway reservations whose event has ended (converts to attendee credits)
        try {
            (new \App\Services\LayawayService())->expireUnpaidLayaways();
        } catch (\Throwable $layErr) {
            error_log("Failed to expire unpaid layaways in processAutoPayouts: " . $layErr->getMessage());
        }

        // 2. Query completed events eligible for auto-payout request:
        // Either:
        // - Event marked completed and updated_at is older than delayMinutes
        // - Or event date + completionHours + delayMinutes is in the past
        $stmt = $db->prepare("
            SELECT e.id, e.organizer_id, e.name as event_name, e.pass_fee, e.date, e.updated_at,
                   u.name as host_name, u.email
            FROM events e
            INNER JOIN users u ON e.organizer_id = u.id
            WHERE e.status = 'completed'
              AND (
                  e.updated_at <= NOW() - INTERVAL :delay MINUTE
                  OR e.date <= NOW() - INTERVAL :total_minutes MINUTE
              )
            ORDER BY e.id ASC
        ");
        $stmt->execute([
            'delay' => (int)$delayMinutes,
            'total_minutes' => (int)($completionHours * 60 + $delayMinutes)
        ]);
        $completedEvents = $stmt->fetchAll(\PDO::FETCH_ASSOC) ?: [];

        $createdPayouts = [];
        $totalAmountCreated = 0.00;
        $hostService = new HostService();

        foreach ($completedEvents as $event) {
            // A. Calculate exact net revenue generated by this specific event strictly from online ticket sold price
            // Direct host issued tickets (is_issued = 1) and platform charges (+5% & extra charge) are excluded
            $salesStmt = $db->prepare("
                SELECT e.pass_fee,
                       COALESCE((
                           SELECT SUM(t.price) FROM tickets t 
                           WHERE t.event_id = e.id AND t.status = 'Paid' AND (t.is_issued = 0 OR t.is_issued IS NULL)
                       ), 0.00) as ticket_sales,
                       COALESCE((
                           SELECT SUM(CASE WHEN COALESCE(t.pass_fee, e.pass_fee) = 1 THEN t.price ELSE t.price * 0.95 END) FROM tickets t 
                           WHERE t.event_id = e.id AND t.status = 'Paid' AND (t.is_issued = 0 OR t.is_issued IS NULL)
                       ), 0.00) as net_sales
                FROM events e
                WHERE e.id = :event_id
            ");
            $salesStmt->execute(['event_id' => $event['id']]);
            $salesData = $salesStmt->fetch(\PDO::FETCH_ASSOC);

            $ticketSales = (float)($salesData['ticket_sales'] ?? 0);
            $eventNetRevenue = isset($salesData['net_sales']) ? round((float)$salesData['net_sales'], 2) : (!empty($salesData['pass_fee']) ? $ticketSales : round($ticketSales * 0.95, 2));

            if ($eventNetRevenue <= 0.00) {
                // Free event or no online ticket sales
                continue;
            }

            // B. Check existing payouts for this event (pending, processed, or completed)
            $payoutStmt = $db->prepare("
                SELECT COALESCE(SUM(amount), 0)
                FROM payouts
                WHERE event_id = :event_id 
                  AND status IN ('pending', 'processed', 'completed')
            ");
            $payoutStmt->execute(['event_id' => $event['id']]);
            $existingPayoutsForEvent = (float)($payoutStmt->fetchColumn() ?: 0.00);

            $unrequestedAmount = round(max(0.00, $eventNetRevenue - $existingPayoutsForEvent), 2);
            if ($unrequestedAmount <= 0.00) {
                // Already requested or disbursed
                continue;
            }

            // C. Verify host's overall available balance to prevent over-withdrawal
            $hostStats = $hostService->getDashboardStats($event['organizer_id']);
            $availableHostBalance = (float)($hostStats['availableBalance'] ?? 0.00);

            $amountToRequest = round(min($unrequestedAmount, $availableHostBalance), 2);
            if ($amountToRequest <= 0.00) {
                continue;
            }

            // D. Insert automatic payout request
            $insStmt = $db->prepare("
                INSERT INTO payouts (organizer_id, event_id, amount, type, status, created_at)
                VALUES (:org_id, :evt_id, :amount, 'auto_completed', 'pending', NOW())
            ");
            $insStmt->execute([
                'org_id' => $event['organizer_id'],
                'evt_id' => $event['id'],
                'amount' => $amountToRequest
            ]);

            $payoutId = (int)$db->lastInsertId();
            $createdPayouts[] = [
                'payout_id' => $payoutId,
                'event_id' => $event['id'],
                'event_name' => $event['event_name'],
                'organizer_id' => $event['organizer_id'],
                'host_name' => $event['host_name'] ?? 'Organizer',
                'amount' => $amountToRequest,
                'pass_fee' => (int)($event['pass_fee'] ?? 1)
            ];
            $totalAmountCreated += $amountToRequest;
        }

        return [
            'enabled' => true,
            'completed_events' => $completedCount,
            'created_payouts' => $createdPayouts,
            'total_amount' => $totalAmountCreated
        ];
    }

    /**
     * Ensure tickets.pass_fee column exists in the database.
     * Prevents fatal 1054 Unknown column 't.pass_fee' exceptions on production.
     */
    public static function ensureTicketsPassFeeColumn(\PDO $db): void
    {
        static $checked = false;
        if ($checked) {
            return;
        }

        try {
            $cols = $db->query("SHOW COLUMNS FROM `tickets` LIKE 'pass_fee'")->fetchAll(\PDO::FETCH_COLUMN);
            if (empty($cols)) {
                $db->exec("ALTER TABLE `tickets` ADD COLUMN `pass_fee` TINYINT(1) NOT NULL DEFAULT 1 AFTER `price`");
                try {
                    $db->exec("UPDATE `tickets` t INNER JOIN `events` e ON t.event_id = e.id SET t.pass_fee = COALESCE(e.pass_fee, 1)");
                } catch (\Throwable $e) {}
            }
            $checked = true;
        } catch (\Throwable $e) {
            // Fail silently if already exists or permission issues
        }
    }

    /**
     * Reconcile past tickets where a promo code discount was applied to the transaction
     * but the tickets were recorded with the undiscounted ticket price.
     * Ensures host sales, payouts, and available balances accurately reflect the discount.
     */
    public static function reconcileDiscountedTickets(\PDO $db): void
    {
        static $reconciled = false;
        if ($reconciled) {
            return;
        }

        try {
            // Find completed transactions that had a promo code discount
            $stmt = $db->query("
                SELECT reference, event_id, subtotal_amount, discount_amount 
                FROM transactions 
                WHERE status = 'completed' AND discount_amount > 0 AND subtotal_amount > 0
            ");
            $discountedTxs = $stmt->fetchAll(\PDO::FETCH_ASSOC) ?: [];

            foreach ($discountedTxs as $tx) {
                $ref = $tx['reference'];
                $discountAmount = (float)$tx['discount_amount'];
                $subtotal = (float)$tx['subtotal_amount'];
                $expectedNetSubtotal = max(0.00, round($subtotal - $discountAmount, 2));

                // Find all tickets associated with this transaction reference
                $ticketStmt = $db->prepare("
                    SELECT id, price, status 
                    FROM tickets 
                    WHERE status_detail LIKE :refPattern
                ");
                $ticketStmt->execute(['refPattern' => '%' . $ref . '%']);
                $tickets = $ticketStmt->fetchAll(\PDO::FETCH_ASSOC) ?: [];

                if (empty($tickets)) {
                    continue;
                }

                $currentTicketTotal = 0.00;
                foreach ($tickets as $tk) {
                    $currentTicketTotal += (float)$tk['price'];
                }

                // If current tickets sum is greater than the discounted amount (i.e. still recorded at undiscounted price)
                if (round($currentTicketTotal, 2) > $expectedNetSubtotal) {
                    $discountRatio = min(1.0, $discountAmount / $subtotal);
                    $remainingExpected = $expectedNetSubtotal;
                    $ticketCount = count($tickets);

                    $updStmt = $db->prepare("UPDATE tickets SET price = :price WHERE id = :id");
                    foreach ($tickets as $idx => $tk) {
                        if ($idx === $ticketCount - 1) {
                            $newPrice = max(0.00, round($remainingExpected, 2));
                        } else {
                            $origPrice = (float)$tk['price'];
                            $newPrice = max(0.00, round($origPrice * (1.0 - $discountRatio), 2));
                            $remainingExpected -= $newPrice;
                        }
                        $updStmt->execute([
                            'price' => $newPrice,
                            'id' => $tk['id']
                        ]);
                    }
                }
            }
            $reconciled = true;
        } catch (\Throwable $e) {
            error_log("Failed to reconcile discounted tickets: " . $e->getMessage());
        }
    }
}